#!/usr/bin/env python3
"""What Microsoft 365 this engine reads, what it could read, and at what cost.

THE QUESTION THIS ANSWERS IS `WHAT NEXT`, AND IT IS NOT THE SAME QUESTION THE
CAPABILITY MANIFEST ANSWERS. The manifest describes what exists: sixteen
capabilities, their endpoints, their permissions, the rules that consume them.
It cannot describe what is missing, because a file built from collectors has no
row for a surface nobody has written a collector for -- and the missing rows are
the ones that decide the order of work. Twenty-one of the engine's rules read
SharePoint. That is not a strategy; it is what happens when the next thing built
is whichever endpoint somebody happened to remember.

TWO HALVES, TWO OWNERS, NEVER BOTH. The collected half is derived here and owned
by the collectors -- editing this document to change it would create a second
answer to a question the manifest already answers. The candidate half is read
from `candidate-surfaces.json`, where every endpoint, version and least
privilege is a citation of a first-party page, and every Graph row has been put
to the service's own schema by `tools/graph-schema-check.py`.

A ROW MOVES FROM THE SECOND HALF TO THE FIRST BY A COLLECTOR BEING WRITTEN, and
it leaves the register in the same commit. A surface described in both files is
a contradiction, and the test suite treats it as one.

THIS DOCUMENT ADDS NO RULES AND PROPOSES NO CONCLUSIONS. `questions` records
what a surface could be asked, not what the answer would mean; a candidate
question is not a rule until it has crossed the readiness gate with a basis, an
authority and fixtures.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from m365_governance import capabilities  # noqa: E402

RULES = ROOT / "src" / "m365_governance" / "data" / "rules"
REGISTER = ROOT / "src" / "m365_governance" / "data" / "candidate-surfaces.json"
OUT = ROOT / "docs" / "CAPABILITY-MAP.md"

SERVICE = {
    "entra": "Microsoft Entra ID",
    "exchange": "Exchange Online",
    "sharepoint": "SharePoint Online",
    "teams": "Microsoft Teams",
    "microsoft-365": "Microsoft 365",
}


def api_version(collector: dict) -> str:
    """Every version a capability actually calls, read from the calls.

    NOT FROM `kind`. The first version of this function returned `powershell`
    for any collector not declared as `graph`, and `licensing` is declared
    `powershell` while making two Graph calls, one of them to `/beta/`. So the
    column that exists to surface beta dependencies hid one on its first run --
    behind a label the collector had chosen for itself. A capability is on beta
    if it calls beta, whatever it is called.
    """
    versions = sorted({"beta" if "/beta/" in r else "v1.0"
                       for r in collector["reads"] if r.startswith("GET /")})
    if collector["kind"] != "graph" or not versions:
        versions = ["powershell"] + versions
    return " + ".join(versions) or "not recorded"


def cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def collected(manifest: dict) -> list[dict]:
    out = []
    for c in manifest["capabilities"]:
        col = c["collector"]
        out.append({
            "service": c["produces"]["workload"],
            "area": c["name"],
            "endpoints": col["reads"],
            "api_version": api_version(col),
            "permissions": col["permissions"],
            "resource": c["produces"]["resource_type"],
            "rules": c.get("consumed_by", []),
            "live": col["live_validation_state"],
            "proof": col["proof"]["state"],
            "limitation": col["validation"]["limitation"],
            "second_surface": col["validation"]["second_surface"],
            "second_surface_state": col["validation"]["second_surface_state"],
        })
    return sorted(out, key=lambda r: (r["service"], r["area"]))


def render(manifest: dict, register: dict) -> str:
    have = collected(manifest)
    want = sorted(register["surfaces"], key=lambda s: (s["service"], s["area"], s["id"]))
    L: list[str] = []
    add = L.append

    add("# Capability map")
    add("")
    add("Generated by `tools/capability-map.py`. Do not edit: the collected half")
    add("is derived from the capability manifest and the candidate half from")
    add("`src/m365_governance/data/candidate-surfaces.json`.")
    add("")
    add(f"{len(have)} capabilities collected today, across "
        f"{len({r['service'] for r in have})} services. "
        f"{len(want)} surfaces recorded as candidates, across "
        f"{len({s['service'] for s in want})}.")
    add("")

    add("## Collected today")
    add("")
    add("| Service | Area | API | Least privilege | Produces | Rules | Live |")
    add("| --- | --- | --- | --- | --- | --- | --- |")
    for r in have:
        perms = ", ".join(r["permissions"])
        add(f"| {SERVICE.get(r['service'], r['service'])} | `{r['area']}` | "
            f"{r['api_version']} | {cell(perms)} | `{r['resource']}` | "
            f"{len(r['rules'])} | {r['live']} |")
    add("")
    add("### What the manifest does not record")
    add("")
    add("Whether a capability works with an **application** identity, a")
    add("**delegated** one, or both. Every collected row above is therefore")
    add("`not established` on that column, and the candidate rows below carry it")
    add("because their sources publish it. This is a real gap: the difference")
    add("decides whether a capability can run unattended, and it is currently")
    add("discoverable only by running the collector.")
    add("")

    add("## Endpoints, by capability")
    add("")
    for r in have:
        add(f"**`{r['area']}`** — {SERVICE.get(r['service'], r['service'])}, "
            f"{r['api_version']}, proof `{r['proof']}`")
        add("")
        for endpoint in r["endpoints"]:
            add(f"- `{endpoint}`")
        add("")
        if r["limitation"]:
            add(f"**Known limitation.** {r['limitation']}.")
            add("")
        add(f"Second surface: {r['second_surface'] or 'none named'} "
            f"(`{r['second_surface_state']}`).")
        add("")

    add("## Candidates, in commercial priority")
    add("")
    add("| Service | Area | Endpoint | API | Least privilege | Identity | Cost |")
    add("| --- | --- | --- | --- | --- | --- | --- |")
    for s in want:
        add(f"| {SERVICE.get(s['service'], s['service'])} | {s['area']} | "
            f"`{cell(s['endpoint'])}` | {s['api_version']} | "
            f"{s['least_privilege']} | {s['identity']} | {s['cost']} |")
    add("")

    for s in want:
        add(f"### `{s['id']}`")
        add("")
        add(s["describes"][0].upper() + s["describes"][1:] + ".")
        add("")
        add("*Could be asked:*")
        add("")
        for q in s["questions"]:
            add(f"- {q}")
        add("")
        add(f"**Known limitation.** {s['limitation']}")
        add("")
        schema = s.get("schema_check")
        if schema:
            add(f"Schema: present in {', '.join(schema['present_in'])}, checked "
                f"{schema['checked_on']}.")
            add("")
        add(f"Authority: <{s['authority']['url']}>, read {s['authority']['read_on']}.")
        add("")

    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero when the written map is not current")
    args = ap.parse_args()

    manifest = capabilities.manifest(RULES)
    register = json.loads(REGISTER.read_text())
    text = render(manifest, register)

    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/CAPABILITY-MAP.md is not current. Run tools/capability-map.py.")
            return 1
        print("the capability map is current")
        return 0

    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
